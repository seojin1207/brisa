-- 1. 분석된 모임(중심 상권) 정보 테이블
CREATE TABLE SHARED_MEETING (
    MEETING_ID       VARCHAR2(36)   PRIMARY KEY,
    PURPOSE          VARCHAR2(20)   NOT NULL,
    HUB_AREA_NAME    VARCHAR2(100)  NOT NULL,
    HUB_LAT          NUMBER(10, 7)  NOT NULL,
    HUB_LNG          NUMBER(10, 7)  NOT NULL,
    AVG_MINUTES      NUMBER(5),
    MAX_DIFF_MINUTES NUMBER(5),
    CREATED_AT       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_MEETING_PURPOSE
        CHECK (PURPOSE IN ('DINING', 'CAFE', 'SHOPPING', 'CULTURE'))
);

-- 2. 보관함에 저장된 즐겨찾기 장소 테이블
CREATE TABLE SHARED_FAVORITE_PLACE (
    FAVORITE_ID       NUMBER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MEETING_ID        VARCHAR2(36)   NOT NULL,
    KAKAO_PLACE_ID    VARCHAR2(50)   NOT NULL,
    PLACE_NAME        VARCHAR2(150)  NOT NULL,
    CATEGORY_NAME     VARCHAR2(150),
    THEME_TITLE       VARCHAR2(100),
    ROAD_ADDRESS_NAME VARCHAR2(255),
    ADDRESS_NAME      VARCHAR2(255),
    PHONE             VARCHAR2(30),
    LAT               NUMBER(10, 7)  NOT NULL,
    LNG               NUMBER(10, 7)  NOT NULL,
    DISTANCE_METERS   NUMBER(6),
    PLACE_URL         VARCHAR2(300),
    CREATED_AT        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_FAV_MEETING
        FOREIGN KEY (MEETING_ID) REFERENCES SHARED_MEETING (MEETING_ID)
        ON DELETE CASCADE,
    CONSTRAINT UQ_MEETING_KAKAO_PLACE
        UNIQUE (MEETING_ID, KAKAO_PLACE_ID)
);

-- 3. 조회 성능 향상을 위한 인덱스
CREATE INDEX IDX_FAV_MEETING_DIST
    ON SHARED_FAVORITE_PLACE (MEETING_ID, DISTANCE_METERS);